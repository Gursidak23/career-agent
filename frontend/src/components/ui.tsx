export function Spinner({ size = 16 }: { size?: number }) {
  return <span className="spinner" style={{ width: size, height: size }} aria-hidden />;
}

export function EmptyState({
  icon,
  title,
  children,
}: {
  icon?: ReactNode;
  title: string;
  children?: ReactNode;
}) {
  return (
    <div className="empty">
      {icon && <div className="empty-icon">{icon}</div>}
      <div className="empty-title">{title}</div>
      {children && <div className="muted">{children}</div>}
    </div>
  );
}

export function scoreTone(score: number): "good" | "mid" | "low" {
  if (score >= 90) return "good";
  if (score >= 70) return "mid";
  return "low";
}

/** Circular 0-100 gauge. */
export function ScoreGauge({ score, size = 112, label }: { score: number; size?: number; label?: string }) {
  const r = (size - 12) / 2;
  const c = 2 * Math.PI * r;
  const pct = Math.max(0, Math.min(100, score)) / 100;
  return (
    <div className={`gauge ${scoreTone(score)}`} style={{ width: size, height: size }}>
      <svg width={size} height={size} viewBox={`0 0 ${size} ${size}`}>
        <circle className="gauge-track" cx={size / 2} cy={size / 2} r={r} />
        <circle
          className="gauge-value"
          cx={size / 2}
          cy={size / 2}
          r={r}
          strokeDasharray={`${c * pct} ${c}`}
          transform={`rotate(-90 ${size / 2} ${size / 2})`}
        />
      </svg>
      <div className="gauge-label">
        <strong>{Math.round(score)}</strong>
        {label && <span>{label}</span>}
      </div>
    </div>
  );
}

